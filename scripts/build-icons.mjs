// Generates src/icons.css and src/components/icons.tsx from lucide's icon data.
// Each icon becomes one <i> element drawn with a CSS mask, instead of an inline <svg> with several child elements:
// the same shapes, but ~60 bytes of HTML per icon instead of ~330 (better text-to-HTML ratio, fewer DOM nodes to hydrate).
// Run again after adding an icon name to the list below (or to a lucide-react import, which no longer exists).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NAMES = {
  AlertCircle: 'circle-alert', ArrowRight: 'arrow-right', ArrowUpDown: 'arrow-up-down', ArrowUpRight: 'arrow-up-right',
  Award: 'award', Battery: 'battery', BookOpen: 'book-open', Building2: 'building-2', Calculator: 'calculator',
  Calendar: 'calendar', Check: 'check', CheckCircle2: 'circle-check', ChevronDown: 'chevron-down',
  ChevronRight: 'chevron-right', ChevronUp: 'chevron-up', Clock: 'clock', Code2: 'code-xml', Coins: 'coins',
  Compass: 'compass', Copy: 'copy', Filter: 'funnel', FolderSync: 'folder-sync', Gauge: 'gauge', Globe: 'globe',
  Info: 'info', Layers: 'layers', Link2: 'link-2', Mail: 'mail', MapPin: 'map-pin', Menu: 'menu',
  MessageCircle: 'message-circle', Mountain: 'mountain', Phone: 'phone', RotateCcw: 'rotate-ccw', Scale: 'scale',
  Search: 'search', ShieldAlert: 'shield-alert', ShieldCheck: 'shield-check', SlidersHorizontal: 'sliders-horizontal',
  Smile: 'smile', Sparkles: 'sparkles', Star: 'star', ThumbsDown: 'thumbs-down', ThumbsUp: 'thumbs-up', Truck: 'truck',
  User: 'user', Weight: 'weight', X: 'x', Zap: 'zap', Minus: 'minus', Plus: 'plus', ShoppingCart: 'shopping-cart', Trash2: 'trash-2',
};
const FILLED = new Set(['Star']); // drawn solid (every use was fill-current)
const BOLD = { Check: 3 }; // extra variant with a heavier stroke: .ic-check.ic-bold

const iconDir = path.join(root, 'node_modules/lucide-react/dist/esm/icons');
const esc = (s) => s.replace(/"/g, "'").replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E');

function svgFor(file, { fill, stroke }) {
  const src = fs.readFileSync(path.join(iconDir, file + '.js'), 'utf8');
  const node = JSON.parse(src.match(/const __iconNode = (\[[\s\S]*?\]);\n/)[1].replace(/([{,]\s*)([a-zA-Z_][\w]*)\s*:/g, '$1"$2":'));
  const body = node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}='${v}'`).join(' ')}/>`).join('');
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='${fill ? 'black' : 'none'}' stroke='black' stroke-width='${stroke}' stroke-linecap='round' stroke-linejoin='round'>${body}</svg>`;
}

let css = `/* Generated by scripts/build-icons.mjs, do not edit. */
/* In the components layer so size utilities such as w-4 still win. */
@layer components {
i[class^=ic-]{display:block;width:24px;height:24px;background-color:currentColor;-webkit-mask:var(--ic) center/contain no-repeat;mask:var(--ic) center/contain no-repeat}
`;
let tsx = `// Generated by scripts/build-icons.mjs, do not edit. Drop-in for the lucide-react icons used on the site.
import type { CSSProperties } from 'react';

type IconProps = { className?: string; size?: number | string; style?: CSSProperties };
const make = (slug: string) =>
  function Icon({ className = '', size, style }: IconProps) {
    return <i className={\`ic-\${slug} \${className}\`} style={size ? { width: size, height: size, ...style } : style} />;
  };

`;
for (const [name, file] of Object.entries(NAMES)) {
  const slug = file;
  css += `.ic-${slug}{--ic:url("data:image/svg+xml,${esc(svgFor(file, { fill: FILLED.has(name), stroke: 2 }))}")}\n`;
  if (BOLD[name]) css += `.ic-${slug}.ic-bold{--ic:url("data:image/svg+xml,${esc(svgFor(file, { fill: false, stroke: BOLD[name] }))}")}\n`;
  tsx += `export const ${name} = make('${slug}');\n`;
}
fs.writeFileSync(path.join(root, 'src/icons.css'), css + '}\n');
fs.writeFileSync(path.join(root, 'src/components/icons.tsx'), tsx);
console.log(`build-icons: ${Object.keys(NAMES).length} icons, ${Math.round(css.length / 1024)} KB of CSS`);
